class Solution {
    public int solution(int num) {
        // 1. int형 오버플로우를 방지하기 위해 입력값을 long 타입으로 변환합니다.
        long n = num;
        
        // 2. 입력값이 애초에 1인 경우 0을 반환합니다.
        if (n == 1) {
            return 0;
        }
        
        // 3. 최대 500번까지 반복 작업을 수행합니다.
        for (int i = 0; i < 500; i++) {
            // 결과가 1이 되면 현재까지의 반복 횟수(i)를 반환합니다.
            if (n == 1) {
                return i;
            }
            
            // 짝수라면 2로 나눕니다.
            if (n % 2 == 0) {
                n /= 2;
            } 
            // 홀수라면 3을 곱하고 1을 더합니다.
            else {
                n = (n * 3) + 1;
            }
        }
        
        // 4. 500번을 반복해도 1이 되지 않으면 -1을 반환합니다.
        return -1;
    }
}